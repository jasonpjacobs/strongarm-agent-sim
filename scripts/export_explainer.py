#!/usr/bin/env python3
"""Export measured waveforms and allowlisted AI responses for the static site.

No credentials, paths, session IDs, raw CLI logs, netlists or PDK files are copied.
The checked-in export means visitors and publishers need no simulator or model.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROPOSAL_FIELDS = ('action','based_on_epoch','diff_mV','evidence_epochs','explanation',
                   'expected_observation','threshold_low_mV','threshold_high_mV')
MEASURE_FIELDS = ('decision','status','external_diff_V','reset_min_V','outp_V','outn_V',
                  'decision_delay_s','hold_window_s','window_points')

def export(run, output):
    run = Path(run)
    report = json.loads((run/'verification.json').read_text())
    manifest = json.loads((run/'live/manifest.json').read_text())
    if report['status'] != 'PASS' or report['replay']['status'] != 'PASS':
        raise ValueError('Publish only a successfully verified run and replay')
    history = report['history']
    choices = []
    for i, item in enumerate(history):
        choices.append(dict(number=i+1, time_ns=round(i*manifest['period_s']*1e9,6),
            response={key:item['proposal'][key] for key in PROPOSAL_FIELDS},
            observation={key:item['result']['trial'][key] for key in MEASURE_FIELDS},
            inference_seconds=item['inference_wall_seconds']))
    stop = {key:report['final_model_response'][key] for key in PROPOSAL_FIELDS}
    final_timing = json.loads((run/f"call-{report['model_calls']:02d}/timing.json").read_text())
    final_time = history[-1]['result']['time_s']
    source = run/'live/waveforms.jsonl'
    points = []
    for line in source.read_text().splitlines():
        row = json.loads(line)
        if row['time'] <= final_time:
            points.append([round(row['time']*1e9,9),round(row['clk'],7),
                           round(row['outp'],7),round(row['outn'],7),
                           round((row['inp_ext']-row['inn'])*1e3,7)])
    if len(points) != report['replay']['identical_points']:
        raise ValueError('Waveform point count differs from verified replay')
    if not all(math.isfinite(v) for point in points for v in point):
        raise ValueError('Non-finite waveform sample')
    if not all(a[0] <= b[0] for a,b in zip(points,points[1:])):
        raise ValueError('Waveform times are not ordered')
    payload = dict(schema=1, model=report['runtime_models'][0], model_calls=report['model_calls'],
        experiment_count=len(choices), duration_ns=round(final_time*1e9,6),
        fixed_offset_mV=manifest['series_offset_V']*1e3, supply_V=1.8, common_mode_V=.9,
        temperature_C=manifest['temperature_C'], corner=manifest['corner'].upper(),
        clock_MHz=1e-6/manifest['period_s'], output_load_fF=10, choices=choices, final_response=stop,
        final_inference_seconds=final_timing['inference_wall_seconds'],
        threshold_bracket_mV=report['observed_threshold_bracket_mV'],
        replay=dict(status=report['replay']['status'], identical_points=report['replay']['identical_points'],
                    model_calls=report['replay']['model_calls']),
        waveforms=dict(columns=['time_ns','clock_V','outp_V','outn_V','external_diff_mV'],points=points),
        provenance=dict(description='Original model-controlled run, not a scripted reconstruction',
            source_waveform_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
            source_verification_sha256=hashlib.sha256((run/'verification.json').read_bytes()).hexdigest(),
            display_precision='All accepted samples; times rounded to 1e-9 ns, voltages to 1e-7 V, differential input to 1e-7 mV. Full-window measurements use the original data.'))
    output = Path(output);output.parent.mkdir(parents=True,exist_ok=True)
    encoded = json.dumps(payload,separators=(',',':'),allow_nan=False).replace('<','\\u003c')
    output.write_text('// Generated by scripts/export_explainer.py. See provenance in the dataset.\nwindow.STRONGARM_EXPERIMENT = '+encoded+';\n')
    return dict(output=str(output),accepted_samples=len(points),choices=len(choices),bytes=output.stat().st_size)

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run',type=Path,required=True,help='Completed original AI run directory')
    parser.add_argument('--output',type=Path,default=ROOT/'docs/assets/experiment.js')
    args=parser.parse_args()
    print(json.dumps(export(args.run,args.output)))
